// Template-driven stand-in for the on-device model. Two curated content packs
// cover the demo classes; any other topic falls back to a generic pack.

export type Mode = 'lesson' | 'rubric' | 'remedial' | 'quiz'
export type Tier = 'standard' | 'remedial' | 'honors'
export type ExportFormat = 'pdf' | 'markdown' | 'csv'
export type Refinement = 'review' | 'simplify' | 'bilingual'

export const MODES: Record<Mode, { label: string; description: string }> = {
  lesson: { label: 'Lesson Plan', description: 'Objectives, warm-up, core activity, exit ticket' },
  rubric: { label: 'Rubric Builder', description: 'Criteria and 4-level performance descriptors' },
  remedial: { label: 'Remedial Worksheet', description: 'Scaffolded recall and guided practice' },
  quiz: { label: 'Quiz Generator', description: 'Multiple-choice items with answer key' },
}

export const TIERS: Record<Tier, { label: string; description: string }> = {
  standard: { label: 'Standard', description: 'On-level pacing and grade-level vocabulary' },
  remedial: { label: 'Simplified for Remedial', description: 'Shorter steps, word banks and sentence starters' },
  honors: { label: 'Advanced Honors', description: 'Extension tasks, data analysis and open inquiry' },
}

export const FORMATS: Record<ExportFormat, { label: string; description: string; ext: string; mime: string }> = {
  pdf: { label: 'PDF Handout', description: 'Print-ready handout, saved via the print dialog', ext: 'pdf', mime: 'application/pdf' },
  markdown: { label: 'Markdown', description: 'Editable .md for notes, docs and wikis', ext: 'md', mime: 'text/markdown' },
  csv: { label: 'LMS CSV sync', description: 'One row per item for LMS import', ext: 'csv', mime: 'text/csv' },
}

export interface DraftSection {
  id: string
  title: string
  body: string
  /** Rendered from structured quiz/rubric data; edited through those fields, not as text. */
  readonly?: boolean
}

export interface DraftParams {
  topic: string
  subject: string
  /** Missing on drafts saved before levels existed; read it through levelOf(). */
  level?: Level
  grade: number
  mode: Mode
  tier: Tier
  format: ExportFormat
  /** One learning objective per line (the backend requires at least one). */
  objectives: string
}

/** Server-side state of a draft generated by the backend (POST /materials/generate). */
export interface MaterialMeta {
  id: string
  kind: MaterialKind
  revision: number
  status: 'draft' | 'reviewed'
  provenance: Provenance
  quiz: QuizQuestion[]
  rubric: RubricCriterion[]
}

export interface Draft extends DraftParams {
  id: string
  title: string
  minutes: number
  sections: DraftSection[]
  refinements: Refinement[]
  createdISO: string
  /** template: built on the device (demo). gemini: generated and stored by the backend. */
  origin: 'template' | 'gemini'
  material?: MaterialMeta
  /** Local edits not yet saved to the backend. */
  dirty?: boolean
}


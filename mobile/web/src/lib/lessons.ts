function bilingualSection(section: DraftSection, topicTl: string): DraftSection {
  const tl = TL[section.id]
  if (!tl) return section
  return {
    ...section,
    title: `${section.title} / ${tl.title}`,
    body: `${section.body}\n\n> Sa Filipino: ${tl.line(topicTl)}`,
  }
}

/** Applies a refinement to the current (possibly hand-edited) sections. */
export function applyRefinement(draft: Draft, refinement: Refinement): Draft {
  if (draft.refinements.includes(refinement)) return draft
  const pack = packFor(draft.topic)
  let sections = draft.sections
  if (refinement === 'review') {
    let added: DraftSection = {
      id: 'review',
      title: 'Review Questions',
      body: pack.review.map((q, i) => `${i + 1}. ${q}`).join('\n'),
    }
    if (draft.refinements.includes('simplify')) added = { ...added, body: simplifyText(added.body) }
    if (draft.refinements.includes('bilingual')) added = bilingualSection(added, pack.topicTl)
    sections = [...sections, added]
  } else if (refinement === 'simplify') {
    sections = sections.map((s) => ({ ...s, body: simplifyText(s.body) }))
  } else {
    sections = sections.map((s) => bilingualSection(s, pack.topicTl))
  }
  return { ...draft, sections, refinements: [...draft.refinements, refinement] }
}

function metaLine(draft: Draft): string {
  return `${gradeLabel(levelOf(draft), draft.grade)} · ${draft.subject} · ${TIERS[draft.tier].label} · ${draft.minutes} min`
}

export function draftToMarkdown(draft: Draft): string {
  const body = draft.sections.map((s) => `## ${s.title}\n\n${s.body}`).join('\n\n')
  return `# ${draft.title}\n\n_${metaLine(draft)}_\n\n${body}\n\n---\nGenerated with GabAI EDU · Edge AI\n`
}

function csvCell(value: string | number): string {
  const text = String(value)
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

export function draftToCsv(draft: Draft): string {
  const rows: (string | number)[][] = [['module', 'grade', 'section', 'order', 'content']]
  for (const section of draft.sections) {
    let order = 0
    for (const block of parseBlocks(section.body)) {
      const lines = 'items' in block ? block.items.map((i) => [i.text, ...i.sub].join(' — ')) : [block.text]
      for (const line of lines) {
        order += 1
        rows.push([draft.title, gradeLabel(levelOf(draft), draft.grade), section.title, order, stripInline(line)])
      }
    }
  }
  return rows.map((r) => r.map(csvCell).join(',')).join('\n') + '\n'
}


function genericPack(topic: string): Pack {
  const t = topic.trim() || 'the topic'
  return {
    topicTl: t,
    task: `${t} performance task`,
    objectives: [
      `Explain the central ideas of ${t}`,
      `Illustrate how ${t} connects to everyday experiences`,
      `Utilize key vocabulary to describe ${t} accurately`,
    ],
    hook: `Pose a real-world question about ${t} and ask: *What do you already know?*`,
    activities: [
      `Station A: Read a short passage on ${t} and annotate three key ideas`,
      `Station B: Construct a concept map that links the main terms of ${t}`,
      'Station C: Apply the concept to a new example and present your reasoning to another group',
    ],
    keyTerms: [],
    extension: `Design a short investigation that tests one claim about ${t}`,
    exit: [`Summarize ${t} in two sentences`, `Write one question you still have about ${t}`],
    review: [
      `What is the most important idea you learned about ${t}?`,
      `How would you explain ${t} to a younger student?`,
      `Give one real-life example of ${t}.`,
    ],
    quiz: [],
    criteria: [
      ['Understanding', `Accurately explains the key ideas of ${t}`],
      ['Application', 'Applies the concept correctly to a new example'],
      ['Evidence', 'Supports claims with data, observations or text references'],
      ['Communication', 'Organizes ideas clearly using subject vocabulary'],
    ],
  }
}

function packFor(topic: string): Pack {
  if (/photosynth|respiration|chloroplast/i.test(topic)) return PHOTO
  if (/stoich|mole/i.test(topic)) return STOICH
  return genericPack(topic)
}

const LETTER = ['A', 'B', 'C', 'D']

function capitalizeFirst(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1)
}

function lessonSections(p: Pack, d: DraftParams, minutes: number): DraftSection[] {
  const core = minutes - 15
  const exitMin = minutes >= 60 ? 10 : 5
  const objectives =
    d.tier === 'remedial'
      ? [`With guided support, ${p.objectives[0].charAt(0).toLowerCase()}${p.objectives[0].slice(1)}`, p.objectives[1]]
      : d.tier === 'honors'
        ? [...p.objectives, 'Analyze evidence to evaluate and justify scientific conclusions']
        : p.objectives
  const warmup = [
    '**5 min** · Whole class',
    `- ${p.hook}`,
    '- Learners write a one-sentence prediction, then share with a partner',
    '- Subsequently, record three ideas on the board to revisit during the exit ticket',
  ]
  if (d.tier === 'remedial') warmup.push('- Provide the sentence starter: *I think … because …*')
  const coreLines = [`**${core} min** · Groups of 4, station rotation`, ...p.activities.map((a, i) => `${i + 1}. ${a}`)]
  coreLines.push('- Facilitate a 5-minute gallery walk so groups can compare their work')
  if (d.tier === 'remedial') {
    if (p.keyTerms.length) coreLines.push(`- **Word bank:** ${p.keyTerms.join(', ')}`)
    coreLines.push('- Give each group a step-by-step checklist for every station')
  }
  if (d.tier === 'honors') coreLines.push(`- **Extension:** ${p.extension}`)
  return [
    {
      id: 'objective',
      title: 'Objective',
      body: `By the end of this ${minutes}-minute session, ${learners(levelOf(d), d.grade)} will be able to:\n${objectives.map((o) => `- ${o}`).join('\n')}`,
    },
    { id: 'warmup', title: 'Warm-up', body: warmup.join('\n') },
    { id: 'core', title: 'Core Activity', body: coreLines.join('\n') },
    {
      id: 'exit',
      title: 'Exit Ticket',
      body: [`**${exitMin} min** · Individual`, `- ${p.exit[0]}`, `- ${p.exit[1]}`, '- Rate your confidence from 1 to 4'].join('\n'),
    },
  ]
}

function remedialSections(p: Pack, d: DraftParams): DraftSection[] {
  const recall = p.keyTerms.length
    ? `- Match each term to its meaning: ${p.keyTerms.join(', ')}`
    : `- List three words you remember about ${d.topic}`
  const practice = [
    '1. Read the worked example together and underline each step',
    `2. ${p.activities[1].replace(/^Station [A-C]: /, '')}`,
    '3. Complete two practice items with a partner, then one on your own',
    '- **Sentence starter:** *The answer is … because …*',
  ]
  if (d.tier === 'honors') practice.push(`- **Challenge:** ${p.extension}`)
  return [
    {
      id: 'objective',
      title: 'Objective',
      body: `${capitalizeFirst(learners(levelOf(d), d.grade))} who need extra support will be able to:\n- ${p.objectives[0]}\n- Utilize key vocabulary accurately in complete sentences`,
    },
    { id: 'warmup', title: 'Recall Warm-up', body: `${recall}\n- Circle the term you find most difficult` },
    { id: 'guided', title: 'Guided Practice', body: practice.join('\n') },
    { id: 'exit', title: 'Exit Ticket', body: `- ${p.exit[0]}\n- Draw a face that shows how confident you feel` },
  ]
}

function quizSections(p: Pack, d: DraftParams): DraftSection[] {
  const count = d.tier === 'remedial' ? 4 : d.tier === 'honors' ? 6 : 5
  const time = d.tier === 'remedial' ? 15 : d.tier === 'honors' ? 25 : 20
  const items = p.quiz.slice(0, count)
  let questions: string
  let key: string
  let numbered = items.length
  if (items.length) {
    questions = items
      .map((it, i) => `${i + 1}. ${it.q}\n  ${it.choices.map((c, ci) => `${LETTER[ci]}. ${c}`).join('   ')}`)
      .join('\n')
    key = items.map((it, i) => `${i + 1}. ${LETTER[it.answer]} · ${it.choices[it.answer]}`).join('\n')
  } else {
    const prompts = [...p.review, p.exit[0]].slice(0, count)
    numbered = prompts.length
    questions = prompts.map((q, i) => `${i + 1}. ${q}\n  *Short answer*`).join('\n')
    key = `- Answers will vary. Accept responses that ${p.objectives[0].charAt(0).toLowerCase()}${p.objectives[0].slice(1)}`
  }
  if (d.tier === 'honors') {
    questions += `\n${numbered + 1}. **Constructed response:** ${p.extension}`
    key += '\n- Constructed response: score with the 4-level rubric'
  }
  return [
    {
      id: 'objective',
      title: 'Objective',
      body: `This ${count}-item quiz checks whether ${learners(levelOf(d), d.grade)} can:\n- ${p.objectives[0]}\n- ${p.objectives[1]}`,
    },
    {
      id: 'directions',
      title: 'Directions',
      body: `- Read each question carefully and choose the best answer\n- Shade the letter of your answer on the answer sheet\n- Time limit: ${time} minutes`,
    },
    { id: 'questions', title: 'Questions', body: questions },
    { id: 'key', title: 'Answer Key', body: key },
  ]
}

function rubricSections(p: Pack, d: DraftParams): DraftSection[] {
  let criteria = p.criteria
  if (d.tier === 'remedial') criteria = criteria.slice(0, 3)
  if (d.tier === 'honors') criteria = [...criteria, ['Extension inquiry', p.extension]]
  const total = criteria.length * 4
  // DepEd cut-offs; a band too narrow to hold a whole score is skipped.
  const scoring = [`- Total: ${total} points (${criteria.length} criteria × 4 levels)`]
  let upper = total
  for (const [pct, label] of [
    [0.9, 'Outstanding'],
    [0.85, 'Very Satisfactory'],
    [0.8, 'Satisfactory'],
    [0.75, 'Fairly Satisfactory'],
  ] as const) {
    const lower = Math.ceil(total * pct)
    if (lower > upper) continue
    scoring.push(`- ${lower === upper ? lower : `${lower}–${upper}`}: ${label}`)
    upper = lower - 1
  }
  scoring.push(`- Below ${upper + 1}: Did Not Meet Expectations`)
  return [
    {
      id: 'objective',
      title: 'Learning Target',
      body: `${capitalizeFirst(learners(levelOf(d), d.grade))} will ${p.objectives[0].charAt(0).toLowerCase()}${p.objectives[0].slice(1)} and communicate their findings clearly.\n- **Task:** ${p.task}`,
    },
    { id: 'criteria', title: 'Criteria', body: criteria.map(([c, desc]) => `- **${c}:** ${desc}`).join('\n') },
    {
      id: 'levels',
      title: 'Performance Levels',
      body: [
        '- **4 · Exemplary:** Exceeds every criterion with precise, well-supported work',
        '- **3 · Proficient:** Meets each criterion with minor errors',
        '- **2 · Developing:** Meets some criteria; key ideas are incomplete',
        '- **1 · Beginning:** Shows limited evidence of understanding',
      ].join('\n'),
    },
    {
      id: 'scoring',
      title: 'Scoring Guide',
      body: scoring.join('\n'),
    },
  ]
}

export function generateDraft(params: DraftParams, createdISO = new Date().toISOString()): Draft {
  const pack = packFor(params.topic)
  const minutes = lessonMinutes(levelOf(params), params.grade)
  const sections =
    params.mode === 'lesson'
      ? lessonSections(pack, params, minutes)
      : params.mode === 'remedial'
        ? remedialSections(pack, params)
        : params.mode === 'quiz'
          ? quizSections(pack, params)
          : rubricSections(pack, params)
  return {
    ...params,
    id: `draft-${Date.parse(createdISO).toString(36)}`,
    title: `${MODES[params.mode].label}: ${params.topic.trim()}`,
    minutes,
    sections,
    refinements: [],
    createdISO,
    origin: 'template',
  }
}

/** Suggested starting objectives for a topic, one per line. */
export function suggestedObjectives(topic: string): string {
  return packFor(topic).objectives.slice(0, 2).join('\n')
}

const SIMPLE_WORDS: [string, string][] = [
  ['utilizes', 'uses'],
  ['utilized', 'used'],
  ['utilize', 'use'],
  ['demonstrates', 'shows'],
  ['demonstrate', 'show'],
  ['subsequently', 'then'],
  ['facilitate', 'lead'],
  ['approximately', 'about'],
  ['comprehend', 'understand'],
  ['illustrate', 'show'],
  ['analyze', 'study'],
  ['evaluate', 'judge'],
  ['determine', 'find'],
  ['construct', 'build'],
  ['converts', 'changes'],
  ['continuous', 'nonstop'],
  ['reactants', 'starting materials'],
  ['justify', 'explain'],
  ['annotate', 'mark up'],
  ['accurately', 'correctly'],
  ['independent and dependent variables', 'what you change and what you measure'],
]

export function simplifyText(text: string): string {
  let out = text
  for (const [from, to] of SIMPLE_WORDS) {
    out = out.replace(new RegExp(`\\b${from}\\b`, 'gi'), (match) =>
      match[0] === match[0].toUpperCase() ? to.charAt(0).toUpperCase() + to.slice(1) : to,
    )
  }
  return out
}

